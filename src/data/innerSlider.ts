export function getDetailSliderSlides(page: InnerDetailPage): InnerSliderSlide[] {
  const images = innerWebAssets[page.slug] ?? [page.image, page.image, page.image]
  const captions = sliderCopy[page.slug] ?? page.highlights

  return images.map((image, index) => {
    const caption = captions[index] ?? captions[index % captions.length] ?? { title: page.title, text: page.intro }
    return {
      image,
      alt: `${page.title}: ${caption.title}`,
      title: caption.title,
      text: caption.text,
    }
  })
}
